from __future__ import annotations
import argparse
import ast
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
SRC=ROOT/'kaggle/src/metalogic_arc3'
PROVENANCE=ROOT/'kaggle/provenance/sources.json'
DEFAULT_OUTPUT=ROOT/'kaggle/agent/my_agent.py'


def clean_module(text: str, remove: tuple[str,...]=()) -> str:
    vendored=set()
    for statement in remove:
        node=ast.parse(statement).body[0]
        if not isinstance(node,ast.ImportFrom):raise ValueError('vendored declarations must be from-imports')
        vendored.add((node.level,node.module))
    skipped=set()
    for node in ast.parse(text).body:
        if not isinstance(node,ast.ImportFrom):continue
        hoisted=node.module=='__future__' and all(alias.name=='annotations' for alias in node.names)
        if hoisted or (node.level,node.module) in vendored:
            skipped.update(range(node.lineno-1,node.end_lineno))
    return ''.join(line for i,line in enumerate(text.splitlines(keepends=True)) if i not in skipped).strip()+'\n'


def render() -> str:
    provenance=json.loads(PROVENANCE.read_text())
    provenance['consequence_acquisition']='intervention-gated-configurations-v2'
    header=('"""Generated self-contained ARC-AGI-3 competition agent.\n'
            'Source of truth: modular files under kaggle/src/. Do not edit this file by hand.\n'
            '"""\nfrom __future__ import annotations\n\n'+f'BUILD_PROVENANCE = {provenance!r}\n\n')
    names=('memory_graph','runtime','memory_controller','consequence_controller','pattern_controller','agent_template')
    remove=tuple('from .'+name+' import _' for name in names)
    return header+'\n'.join(clean_module((SRC/(name+'.py')).read_text(),remove) for name in names)


def build(output: Path) -> Path:
    output.parent.mkdir(parents=True,exist_ok=True);source=render()
    if any(isinstance(n,ast.ImportFrom) and n.level for n in ast.walk(ast.parse(source))):
        raise ValueError('standalone agent contains unvendored relative imports')
    compile(source,str(output),'exec');output.write_text(source);return output


def main() -> None:
    p=argparse.ArgumentParser();p.add_argument('--output',type=Path,default=DEFAULT_OUTPUT)
    print(build(p.parse_args().output))
if __name__=='__main__':main()
